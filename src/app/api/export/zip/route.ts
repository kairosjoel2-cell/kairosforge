import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { getSessionUserId } from "@/lib/auth";
import JSZip from "jszip";

interface FileEntry { path: string; content: string }

export async function GET(req: NextRequest) {
  const userId = await getSessionUserId();
  if (!userId) return NextResponse.json({ error: "Not authenticated" }, { status: 401 });
  const id = new URL(req.url).searchParams.get("projectId");
  if (!id) return NextResponse.json({ error: "projectId required" }, { status: 400 });

  const project = await prisma.project.findFirst({ where: { id, userId } });
  if (!project) return NextResponse.json({ error: "Not found" }, { status: 404 });

  const files = project.files as unknown as FileEntry[];
  const zip = new JSZip();
  for (const f of files) zip.file(f.path, f.content);

  zip.file("README.md", `# ${project.name}\n\nGenerated by KAIROSFORGE AI.\n\n## Prompt\n\n${project.prompt}\n\n## How to run\n\n${
    project.framework === "html"
      ? "Open `index.html` in a browser, or serve with `npx serve .`."
      : "This is a React project.\n\n1. `npm install`\n2. `npm run dev`\n\n(You may need to scaffold a Vite wrapper — see kairosforge docs.)"
  }\n`);

  const buffer = await zip.generateAsync({ type: "nodebuffer" });

  return new NextResponse(buffer as unknown as BodyInit, {
    headers: {
      "Content-Type": "application/zip",
      "Content-Disposition": `attachment; filename="${project.name.replace(/[^a-zA-Z0-9-_]/g, "-")}.zip"`,
    },
  });
}
